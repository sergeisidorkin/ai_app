def extract_line_end_spaces(docx_bytes: bytes, progress=None) -> frozenset[int]:
    """Смещения обычных пробелов, после которых Word переносит визуальную строку."""
    parts = _read_zip(docx_bytes)
    xml = parts.get(DOCUMENT_XML)
    if not xml:
        raise DocxCommentError("В файле нет word/document.xml.")
    try:
        root = etree.fromstring(xml)
    except etree.XMLSyntaxError as exc:
        raise DocxCommentError("Некорректный word/document.xml.") from exc
    theme = _theme_fonts(parts.get("word/theme/theme1.xml"))
    styles = _style_sheet(parts.get("word/styles.xml"), theme)
    numbering = _numbering_map(parts.get("word/numbering.xml"))
    body = root.find(w("body"))
    if body is None:
        return frozenset()
    paragraphs = list(body.iter(w("p")))
    boxes = _paragraph_section_boxes(body, paragraphs)
    ends: set[int] = set()
    offset = 0
    total = len(paragraphs)
    if progress is not None:
        progress(0, total)
    for index, (paragraph, (page_w, margin_l, margin_r)) in enumerate(zip(paragraphs, boxes), start=1):
        usable = max(page_w - margin_l - margin_r, 200)
        para_w = _paragraph_widths(paragraph, usable, styles, numbering)
        items, offset = _paragraph_items(paragraph, offset, styles)
        ends.update(
            _wrap_space_offsets(
                items,
                para_w[0],
                para_w[1],
                justify=_paragraph_justified(paragraph, styles),
            )
        )
        offset += 1
        if progress is not None and (index == total or index % 40 == 0):
            progress(index, total)
    return frozenset(ends)


