def _rpr_attrs(r_pr: etree._Element | None, theme: dict | None = None) -> dict:
    if r_pr is None:
        return {}
    out: dict = {}
    sz = _sz_val(r_pr.find(w("sz")))
    if sz:
        out["sz"] = sz
    sz_cs = _sz_val(r_pr.find(w("szCs")))
    if sz_cs:
        out["sz_cs"] = sz_cs
    bold = _on_off(r_pr.find(w("b")))
    if bold is not None:
        out["bold"] = bold
    bold_cs = _on_off(r_pr.find(w("bCs")))
    if bold_cs is not None:
        out["bold_cs"] = bold_cs
    italic = _on_off(r_pr.find(w("i")))
    if italic is not None:
        out["italic"] = italic
    italic_cs = _on_off(r_pr.find(w("iCs")))
    if italic_cs is not None:
        out["italic_cs"] = italic_cs
    slots = _font_slots(r_pr.find(w("rFonts")), theme)
    if slots:
        out["fonts"] = slots
    spacing = _int_attr(r_pr.find(w("spacing")), "val", None)
    if spacing is not None:
        out["spacing"] = spacing
    scale = _int_attr(r_pr.find(w("w")), "val", None)
    if scale is not None:
        out["scale"] = scale
    caps = _on_off(r_pr.find(w("caps")))
    if caps is not None:
        out["caps"] = caps
    small_caps = _on_off(r_pr.find(w("smallCaps")))
    if small_caps is not None:
        out["small_caps"] = small_caps
    vert = r_pr.find(w("vertAlign"))
    if vert is not None:
        kind = (vert.get(w("val")) or "").strip().lower()
        if kind in ("subscript", "superscript"):
            out["vert_align"] = kind
            # Размер в этом же rPr уже уменьшен. Если его нет, Word берёт 65% кегля.
            if "sz" not in out:
                out["script_scale"] = 65
    kern = r_pr.find(w("kern"))
    if kern is not None:
        # Минимальный кегль в полупунктах, с которого Word применяет кернинг.
        out["kern"] = _sz_val(kern) or 0
    r_style = r_pr.find(w("rStyle"))
    if r_style is not None:
        style_id = r_style.get(w("val")) or ""
        if style_id:
            out["rStyle"] = style_id
    return out


def _font_slots(r_fonts: etree._Element | None, theme: dict | None) -> dict:
    """Явное имя слота перекрывает тему. Пустой слот не затирает унаследованный."""
    if r_fonts is None:
        return {}
    out = {}
    for slot, name_attr, theme_attr in _SLOT_ATTRS:
        explicit = r_fonts.get(w(name_attr)) or ""
        if explicit:
            out[slot] = {"name": explicit, "scheme": ""}
            continue
        mapped = _THEME_FACE.get(r_fonts.get(w(theme_attr)) or "")
        if not mapped:
            continue
        scheme, face_key = mapped
        name = ((theme or {}).get(scheme) or {}).get(face_key) or ""
        out[slot] = {"name": name, "scheme": scheme}
    return out


def _font_slot(ch: str) -> str:
    """Слот Word: ascii до U+007F, сложное письмо, иероглифы, иначе hAnsi (в том числе кириллица)."""
    code = ord(ch)
    if code <= 0x7F:
        return "ascii"
    if _is_complex_script(code):
        return "cs"
    if _is_east_asian(code):
        return "eastAsia"
    return "hAnsi"


def _is_complex_script(code: int) -> bool:
    return (
        0x0590 <= code <= 0x08FF
        or 0x0900 <= code <= 0x109F
        or 0x1780 <= code <= 0x17FF
        or 0xFB1D <= code <= 0xFDFF
        or 0xFE70 <= code <= 0xFEFF
    )


def _is_east_asian(code: int) -> bool:
    return (
        0x1100 <= code <= 0x11FF
        or 0x2E80 <= code <= 0x9FFF
        or 0xAC00 <= code <= 0xD7AF
        or 0xF900 <= code <= 0xFAFF
        or 0xFE30 <= code <= 0xFE4F
        or 0xFF00 <= code <= 0xFFEF
        or 0x20000 <= code <= 0x3FFFD
    )


def _theme_script(ch: str) -> str:
    code = ord(ch)
    if 0x0400 <= code <= 0x052F or 0x2DE0 <= code <= 0x2DFF or 0xA640 <= code <= 0xA69F:
        return "Cyrl"
    if 0x0370 <= code <= 0x03FF or 0x1F00 <= code <= 0x1FFF:
        return "Grek"
    if 0x0590 <= code <= 0x05FF:
        return "Hebr"
    if 0x0600 <= code <= 0x06FF or 0x0750 <= code <= 0x077F or 0x08A0 <= code <= 0x08FF:
        return "Arab"
    if 0x3040 <= code <= 0x30FF:
        return "Jpan"
    if 0xAC00 <= code <= 0xD7AF or 0x1100 <= code <= 0x11FF:
        return "Hang"
    if 0x4E00 <= code <= 0x9FFF:
        return "Hans"
    return ""


def _typeface(fmt: dict, ch: str, theme: dict | None) -> str:
    fonts = fmt.get("fonts") or {}
    slot = _font_slot(ch)
    spec = fonts.get(slot)
    if not spec:
        if slot == "ascii":
            spec = fonts.get("hAnsi")
        else:
            spec = fonts.get("hAnsi") or fonts.get("ascii")
    if not spec:
        return ""
    scheme = spec.get("scheme") or ""
    script = _theme_script(ch) if scheme else ""
    if script:
        face = ((theme or {}).get(scheme) or {}).get(script) or ""
        if face:
            return face
    return spec.get("name") or ""


def _glyph_props(fmt: dict, ch: str) -> tuple[int, bool, bool]:
    complex_script = _font_slot(ch) == "cs"
    if complex_script and fmt.get("sz_cs"):
        size = fmt["sz_cs"]
    else:
        size = fmt.get("sz") or DEFAULT_SZ_HP
    if complex_script and "bold_cs" in fmt:
        bold = bool(fmt["bold_cs"])
    else:
        bold = bool(fmt.get("bold"))
    if complex_script and "italic_cs" in fmt:
        italic = bool(fmt["italic_cs"])
    else:
        italic = bool(fmt.get("italic"))
    return size, bold, italic


def _advance(fmt: dict, ch: str, theme: dict | None) -> float:
    face = _typeface(fmt, ch, theme)
    size, bold, italic = _glyph_props(fmt, ch)
    measure = ch
    small = False
    if fmt.get("caps"):
        measure = ch.upper()
    elif fmt.get("small_caps") and ch.isalpha() and ch != ch.upper():
        measure = ch.upper()
        small = True
    width = _char_width(
        measure,
        size,
        bold=bold,
        italic=italic,
        font=face,
        mono=_is_mono(face),
    )
    if small:
        width = width * 80 / 100
    script = fmt.get("script_scale")
    if script not in (None, 100):
        width = width * int(script) / 100
    scale = fmt.get("scale")
    if scale not in (None, 100):
        width = width * int(scale) // 100
    spacing = int(fmt.get("spacing") or 0)
    if spacing:
        width = max(0, width + spacing)
    return width


def _on_off(el: etree._Element | None) -> bool | None:
    if el is None:
        return None
    val = (el.get(w("val")) or "").strip().lower()
    if val in ("0", "false", "off"):
        return False
    return True


def _is_mono(font: str) -> bool:
    return font.strip().lower() in _MONO_FONTS


def _sz_val(sz: etree._Element | None) -> int | None:
    if sz is None:
        return None
    try:
        value = int(sz.get(w("val")) or 0)
    except ValueError:
        return None
    return value if value > 0 else None


def _ind_of(p_pr: etree._Element | None) -> dict[str, int]:
    if p_pr is None:
        return {}
    ind = p_pr.find(w("ind"))
    if ind is None:
        return {}
    out = {}
    for name in ("left", "right", "firstLine", "hanging", "start", "end"):
        value = _int_attr(ind, name, None)
        if value is not None:
            out["left" if name == "start" else "right" if name == "end" else name] = value
    return out


def _tbl_cell_mar(tbl_pr: etree._Element | None) -> tuple[int, int] | None:
    if tbl_pr is None:
        return None
    mar = tbl_pr.find(w("tblCellMar"))
    if mar is None:
        return None
    left = _dxa(mar.find(w("left")))
    right = _dxa(mar.find(w("right")))
    if left is None and right is None:
        return None
    return (left or 0, right or 0)


def _table_style_margins(tbl: etree._Element, styles: dict) -> tuple[int, int]:
    direct = _tbl_cell_mar(tbl.find(w("tblPr")))
    if direct is not None:
        return direct
    style_el = tbl.find(f"{w('tblPr')}/{w('tblStyle')}")
    style_id = (style_el.get(w("val")) or "") if style_el is not None else ""
    if not style_id:
        style_id = styles.get("default_t_style") or ""
    seen: set[str] = set()
    while style_id and style_id not in seen:
        seen.add(style_id)
        pair = (styles.get("tbl_mar") or {}).get(style_id)
        if pair is not None:
            return pair
        style_id = (styles.get("based") or {}).get(style_id, "")
    return (0, 0)


def _table_width(tbl: etree._Element, columns: list[int], usable: int) -> int:
    tbl_w = tbl.find(f"{w('tblPr')}/{w('tblW')}")
    kind = ((tbl_w.get(w("type")) if tbl_w is not None else "") or "dxa").lower()
    value = _int_attr(tbl_w, "w", 0) if tbl_w is not None else 0
    if kind in ("dxa", "") and value > 0:
        return value
    if kind == "pct" and value > 0 and usable > 0:
        return usable * value // 5000
    if columns:
        return sum(columns)
    return usable


def _cell_width(paragraph: etree._Element, styles: dict | None = None, usable: int = 0) -> int | None:
    """Ширина текста в ячейке: сетка или доля таблицы минус поля ячейки."""
    styles = styles or {}
    node = paragraph.getparent()
    tc = None
    while node is not None:
        if node.tag == w("tc"):
            tc = node
            break
        if node.tag == w("body"):
            return None
        node = node.getparent()
    if tc is None:
        return None
    tbl = tc.getparent()
    while tbl is not None and tbl.tag != w("tbl"):
        tbl = tbl.getparent()
    if tbl is None:
        return None
    grid = tbl.find(w("tblGrid"))
    columns = []
    if grid is not None:
        for col in grid.findall(w("gridCol")):
            try:
                columns.append(int(col.get(w("w")) or 0))
            except ValueError:
                columns.append(0)
    row = tc.getparent()
    index = 0
    if row is not None:
        for cell in row:
            if cell.tag != w("tc"):
                continue
            if cell is tc:
                break
            index += _grid_span(cell)
    span = _grid_span(tc)
    width = 0
    if columns and index < len(columns):
        width = sum(columns[index:index + span])
    if width <= 0:
        tc_w = tc.find(f"{w('tcPr')}/{w('tcW')}")
        kind = ((tc_w.get(w("type")) if tc_w is not None else "") or "dxa").lower()
        value = _int_attr(tc_w, "w", 0) if tc_w is not None else 0
        if kind in ("dxa", "") and value > 0:
            width = value
        elif kind == "pct" and value > 0:
            width = _table_width(tbl, columns, usable) * value // 5000
    if width <= 0:
        return None
    left, right = _table_style_margins(tbl, styles)
    tc_mar = tc.find(f"{w('tcPr')}/{w('tcMar')}")
    if tc_mar is not None:
        own_left = _dxa(tc_mar.find(w("left")))
        own_right = _dxa(tc_mar.find(w("right")))
        if own_left is not None:
            left = own_left
        if own_right is not None:
            right = own_right
    return max(width - left - right, 200)


def _grid_span(cell: etree._Element) -> int:
    span = cell.find(f"{w('tcPr')}/{w('gridSpan')}")
    if span is None:
        return 1
    try:
        return max(int(span.get(w("val")) or 1), 1)
    except ValueError:
        return 1


def _dxa(node: etree._Element | None) -> int | None:
    if node is None:
        return None
    w_type = (node.get(w("type")) or "dxa").lower()
    if w_type not in ("dxa", ""):
        return None
    return _int_attr(node, "w", None)


def _drawing_width(node: etree._Element) -> int:
    for extent in node.iter(f"{{{WP_NS}}}extent"):
        cx = extent.get("cx")
        if cx:
            try:
                return max(int(cx) // 635, 0)
            except ValueError:
                return 0
    return 0


def _div_round(value: int, divisor: int = 1000) -> int:
    """Округление к ближайшему. Ширина знака в Word не обрезается вниз."""
    if value >= 0:
        return (value + divisor // 2) // divisor
    return -((-value + divisor // 2) // divisor)


def _char_width(
    ch: str,
    sz_hp: int,
    bold: bool = False,
    italic: bool = False,
    font: str = "",
    mono: bool = False,
) -> int:
    em = max(int(sz_hp or DEFAULT_SZ_HP), 1) * 10
    measured, from_face = _measured_units(font, ch, bold=bold, italic=italic)
    if mono:
        units = _MONO_EM_BY_FONT.get((font or "").strip().lower(), _MONO_EM)
        from_face = False
    elif measured is not None:
        units = measured
    elif ch in _CHAR_EM:
        units = _CHAR_EM[ch]
    elif ch.isdigit():
        units = 500
    elif ch in _NARROW:
        units = 280
    elif ch in _WIDE:
        units = 780
    elif ch.isalpha() and ch == ch.upper() and ch.lower() != ch:
        units = _UPPER_EM
    elif ch.isalpha():
        units = _LETTER_EM
    else:
        units = 400
    # Доля em, без округления каждого знака: сумма округлений
    # на длинной строке уезжает на десятки твипов.
    width = em * units / 1000
    # 4% и 8% — запасной масштаб, когда в таблице нет этого начертания.
    if not from_face:
        if bold:
            width = width * _BOLD_NUM / 100
        if italic:
            width = width * _ITALIC_NUM / 100
    return width


def _font_key(font: str) -> str:
    name = (font or "").strip().lower().split("(")[0].strip()
    return _FONT_KEYS.get(name, "")


def _kern_twips(prev_face: str, face: str, prev: str, ch: str, fmt: dict) -> int:
    """Кернинг пары соседних знаков, в твипах. У разных гарнитур пары нет."""
    if not prev or not ch:
        return 0
    key = _font_key(prev_face)
    if not key or key != _font_key(face):
        return 0
    units = _KERNING.get(key, {}).get(prev + ch)
    if not units:
        return 0
    size, _, _ = _glyph_props(fmt, ch)
    adj = _div_round(max(int(size), 1) * 10 * units)
    script = fmt.get("script_scale")
    if script not in (None, 100):
        adj = adj * int(script) // 100
    return adj


def _measured_units(font: str, ch: str, bold: bool = False, italic: bool = False) -> tuple[int | None, bool]:
    """Доли em и признак, что это метрики нужного начертания, а не синтетический масштаб."""
    name = (font or "").strip().lower().split("(")[0].strip()
    key = _FONT_KEYS.get(name)
    if not key:
        return None, False
    if bold and italic:
        suffix = "-bi"
    elif italic:
        suffix = "-i"
    elif bold:
        suffix = "-b"
    else:
        suffix = ""
    if suffix:
        units = _FONT_UNITS.get(key + suffix, {}).get(ch)
        if units is not None:
            return units, True
    return _FONT_UNITS.get(key, {}).get(ch), False


def _in_descendant_p(node: etree._Element, paragraph: etree._Element) -> bool:
    parent = node.getparent()
    while parent is not None and parent is not paragraph:
        if parent.tag == w("p"):
            return True
        parent = parent.getparent()
    return False


def _int_attr(node: etree._Element | None, name: str, default):
    if node is None:
        return default
    raw = node.get(w(name))
    if raw is None:
        return default
    try:
        return int(raw)
    except ValueError:
        return default
